import 'dart:ui';

import 'package:flutter_test/flutter_test.dart';
import 'package:pip_garden/src/garden/image_sprites.dart';

import 'sprite_art/plants.dart';
import 'sprite_art/wash.dart';

/// Builds every app-icon file both stores need from one painted seedling.
///
///     flutter test tool/generate_icons.dart
///
/// The seedling comes from `paintIconSeedling` in `tool/sprite_art/plants.dart`
/// at 1024px, tinted through `ImageSpriteArt`. Every size is derived from it.
///
/// Android adaptive icons: launchers only guarantee the central 66dp of the
/// 108dp foreground, so the seedling stays inside that and the background is
/// a flat fill. iOS gets an opaque full-bleed icon (it masks the corners).

const Color _ground = Color(0xFFE8F0E2);
const Color _green = Color(0xFF6B8E5A);
const Color _soil = Color(0xFF8B6F47);

const Map<String, double> _densities = {
  'mdpi': 1,
  'hdpi': 1.5,
  'xhdpi': 2,
  'xxhdpi': 3,
  'xxxhdpi': 4,
};

/// (points, scale), matching the project's `Contents.json`.
const List<(double, int)> _iosSizes = [
  (20, 1), (20, 2), (20, 3),
  (29, 1), (29, 2), (29, 3),
  (40, 1), (40, 2), (40, 3),
  (60, 2), (60, 3),
  (76, 1), (76, 2),
  (83.5, 2),
  (1024, 1),
];

late ImageSpriteArt _mark;

void main() {
  test('generate the app icons', () async {
    _mark = await _paintMark();

    // --- Android, legacy: the whole mark on its ground, one per density.
    for (final entry in _densities.entries) {
      final side = (48 * entry.value).round();
      await _write(
        'android/app/src/main/res/mipmap-${entry.key}/ic_launcher.png',
        side,
        (canvas) {
          _fill(canvas, side, _ground);
          _seedling(canvas, side.toDouble(), inset: 0.16);
        },
      );
    }

    // --- Android, adaptive: two 108dp layers, the mark inside the safe circle.
    for (final entry in _densities.entries) {
      final side = (108 * entry.value).round();

      await _write(
        'android/app/src/main/res/mipmap-${entry.key}/ic_launcher_background.png',
        side,
        (canvas) => _fill(canvas, side, _ground),
      );

      await _write(
        'android/app/src/main/res/mipmap-${entry.key}/ic_launcher_foreground.png',
        side,
        // Keeps the mark inside the 66dp safe zone.
        (canvas) => _seedling(canvas, side.toDouble(), inset: 0.28),
      );
    }

    File('android/app/src/main/res/mipmap-anydpi-v26/ic_launcher.xml')
      ..parent.createSync(recursive: true)
      ..writeAsStringSync('''
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_icons.dart. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@mipmap/ic_launcher_background"/>
    <foreground android:drawable="@mipmap/ic_launcher_foreground"/>
    <monochrome android:drawable="@mipmap/ic_launcher_foreground"/>
</adaptive-icon>
''');

    // --- iOS: fully opaque; the system rounds the corners.
    for (final (points, scale) in _iosSizes) {
      final side = (points * scale).round();
      final name = points == points.roundToDouble()
          ? '${points.toInt()}x${points.toInt()}'
          : '${points}x$points';

      await _write(
        'ios/Runner/Assets.xcassets/AppIcon.appiconset/'
        'Icon-App-$name@${scale}x.png',
        side,
        (canvas) {
          _fill(canvas, side, _ground);
          _seedling(canvas, side.toDouble(), inset: 0.16);
        },
      );
    }

    // ignore: avoid_print
    print('wrote ${_densities.length * 3} Android files and '
        '${_iosSizes.length} iOS icons');
  });
}

/// [inset] is a fraction of [side] on each edge.
void _seedling(Canvas canvas, double side, {required double inset}) {
  final box = Rect.fromLTWH(
    side * inset,
    side * inset,
    side * (1 - inset * 2),
    side * (1 - inset * 2),
  );
  _mark.paintTinted(canvas, box, const [_green, _green, _soil]);
}

Future<ImageSpriteArt> _paintMark() async {
  final sheet = Sheet(1024, finish: Finish.paperCut);
  await paintIconSeedling(sheet);

  final scratch = Directory.systemTemp.createTempSync('icon_mark');
  try {
    final art = '${scratch.path}/mark.png';
    final roles = '${scratch.path}/mark.roles.png';
    sheet.write(art: art, mask: roles);
    return ImageSpriteArt(
      art: await _decode(art),
      roles: await _decode(roles),
      footprint: const Rect.fromLTWH(0, 0, 1, 1),
    );
  } finally {
    scratch.deleteSync(recursive: true);
  }
}

Future<Image> _decode(String path) async {
  final codec = await instantiateImageCodec(File(path).readAsBytesSync());
  final frame = await codec.getNextFrame();
  codec.dispose();
  return frame.image;
}

void _fill(Canvas canvas, int side, Color colour) => canvas.drawRect(
      Rect.fromLTWH(0, 0, side.toDouble(), side.toDouble()),
      Paint()..color = colour,
    );

Future<void> _write(String path, int side, void Function(Canvas) draw) async {
  final recorder = PictureRecorder();
  draw(Canvas(recorder));
  final picture = recorder.endRecording();

  final image = await picture.toImage(side, side);
  picture.dispose();

  final png = await image.toByteData(format: ImageByteFormat.png);
  image.dispose();

  File(path)
    ..parent.createSync(recursive: true)
    ..writeAsBytesSync(png!.buffer.asUint8List());
}
